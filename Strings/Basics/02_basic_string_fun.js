// MEANING OF STRING
// A string is simply a sequence of characters.
// Think of it like a word or sentence where each letter has its own position (index).

let str = "hello";

// Memory looks like this:
/*
| Index     | 0 | 1 | 2 | 3 | 4 |
| --------- | - | - | - | - | - |
| Character | h | e | l | l | o |
*/
// Each character can be accessed using its index.

console.log(str[0]); // h
console.log(str[3]); // l

