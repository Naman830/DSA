/*
Stack

A Stack is a linear data structure that follows the LIFO principle.
LIFO = Last In, First Out

    ┌─────┐  ← 4 (Top)
    │  4  │
    ├─────┤
    │  3  │
    ├─────┤
    │  2  │
    ├─────┤
    │  1  │
    └─────┘

If you want to remove a plate, you must remove the top one first.
Remove order:
4 → 3 → 2 → 1
*/

/*
Operations in Stack

1. Push (Insert)        [Adds an element on the top.]
2. Pop (Remove)         [Removes the top element.]
3. Peek / Top           [Returns the top element without removing it.]
4. isEmpty()            [Checks whether the stack is empty.]
*/
