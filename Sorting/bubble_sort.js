// Bubble Sort works by repeatedly comparing two side-by-side elements and swapping them if they are in the wrong order.

/*
Pseudo Code

bubbleSort(arr):
    n = length of arr

    for i from 0 to n - 2:
        for j from 0 to n - 2:
            if arr[j] > arr[j + 1]:
                swap arr[j] and arr[j + 1]

    return arr
*/
